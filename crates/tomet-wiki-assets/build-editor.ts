import { build } from "npm:vite@6";
import { svelte } from "npm:@sveltejs/vite-plugin-svelte@5";
import "npm:svelte@5";
import "npm:@tomet/cms@^0.1.0";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";
import { gzipSync } from "node:zlib";
import { Buffer } from "node:buffer";

const __dirname = dirname(fileURLToPath(import.meta.url));

// Resolve @tomet/cms from npm package without any external repository paths
const require = createRequire(import.meta.url);
const tometCmsEntry = require.resolve("@tomet/cms");
const tometCmsDir = dirname(tometCmsEntry);
const wasmPath = resolve(tometCmsDir, "pkg/tomet_cms_js_bg.wasm");
const jsBindingsPath = resolve(tometCmsDir, "pkg/tomet_cms_js.js");

function inlineWasmPlugin(wasmFilePath: string) {
  const virtualId = "virtual:tomet-cms-wasm";
  const resolvedId = "\0" + virtualId;
  return {
    name: "inline-tomet-cms-wasm",
    resolveId(id: string) {
      if (id === virtualId) return resolvedId;
    },
    load(id: string) {
      if (id === resolvedId) {
        const rawBytes = Deno.readFileSync(wasmFilePath);
        const gzipped = gzipSync(rawBytes);
        const b64 = Buffer.from(gzipped).toString("base64");
        return `
          const b64 = "${b64}";
          const binary = atob(b64);
          const compressed = new Uint8Array(binary.length);
          for (let i = 0; i < binary.length; i++) {
            compressed[i] = binary.charCodeAt(i);
          }
          let cachedPromise = null;
          export async function getWasmBytes() {
            if (!cachedPromise) {
              cachedPromise = (async () => {
                const stream = new Response(compressed).body.pipeThrough(new DecompressionStream("gzip"));
                const buf = await new Response(stream).arrayBuffer();
                return new Uint8Array(buf);
              })();
            }
            return cachedPromise;
          }
          export default getWasmBytes;
        `;
      }
    },
  };
}

console.log("Compiling Svelte 5 Wiki Editor Bundle with Deno & Vite 6...");

await build({
  root: __dirname,
  plugins: [
    inlineWasmPlugin(wasmPath),
    svelte(),
  ],
  resolve: {
    conditions: ["browser", "production"],
    alias: {
      "@tomet/cms/pkg": jsBindingsPath,
    },
  },
  build: {
    outDir: resolve(__dirname, "assets"),
    emptyOutDir: false,
    cssCodeSplit: false,
    minify: "esbuild",
    cssMinify: true,
    rollupOptions: {
      input: resolve(__dirname, "ui/main.ts"),
      output: {
        format: "es",
        entryFileNames: "wiki-editor.js",
        assetFileNames: "wiki-editor[extname]",
      },
    },
  },
  define: {
    "process.env.NODE_ENV": '"production"',
  },
});

// The WASM binary is already embedded into wiki-editor.js as an inlined module.
// Remove any redundant standalone .wasm file generated by Vite's asset scanner.
const wasmOut = resolve(__dirname, "assets/wiki-editor.wasm");
try {
  Deno.removeSync(wasmOut);
} catch {
  // Ignore if not present
}

console.log("Done! Output generated at assets/wiki-editor.js and assets/wiki-editor.css");
